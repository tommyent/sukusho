import Foundation

/// What a clipboard history entry holds: only what the pasteboard itself tells
/// apart. Links and colours are read from the text when shown (`textForm`), so
/// a better classifier never needs a database migration.
nonisolated enum ClipboardEntryKind: String, Sendable, CaseIterable {
    case image, text, files, snippet
}

/// How a text entry is shown.
nonisolated enum ClipboardTextForm: Equatable, Sendable {
    case plain, link, color(hex: String)
}

/// Decides from the pasteboard's types and source alone whether a copy is
/// kept and what to read. Nothing here reads what was copied.
nonisolated enum ClipboardCapturePolicy {
    /// nspasteboard.org's markers, and the older transient and confidential types it lists: never kept.
    /// Another history's paste-back carries AutoGeneratedType when that history follows the convention.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    /// Ignored until the user changes the list in Settings: Keychain Access, Passwords, 1Password.
    static let defaultIgnoredApps = ["com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password"]
    static let sourceType = "org.nspasteboard.source"
    /// Stamped on what Sukusho writes from history, so the monitor doesn't record it again.
    static let captureNameType = "com.tommyent.Sukusho.capture-name"
    static let ownType = "com.tommyent.Sukusho.clipboard-history"
    /// Universal Clipboard's marker (community-documented, not Apple API).
    static let remoteType = "com.apple.is-remote-clipboard"
    static let fileURLType = "public.file-url"
    static let textTypes = ["public.utf8-plain-text", "public.url"]
    static let colorType = "com.apple.cocoa.pasteboard.color"
    /// Image kinds kept, best first; TIFF is stored as PNG.
    static let imageTypes = ["public.png", "public.jpeg", "public.heic", "com.compuserve.gif", "public.tiff"]
    static let richTextTypes = ["public.rtf", "public.html"]

    static let maxImageBytes = 50 * 1024 * 1024
    static let maxImagePixels = 200_000_000
    static let maxTextBytes = 2 * 1024 * 1024
    static let maxRichTextBytes = 5 * 1024 * 1024
    /// A Finder select-all keeps its first 500 files, not ten thousand rows.
    static let maxFiles = 500

    enum Skip: Equatable, Sendable {
        case privateType(String), ignoredApp(String), nothingKept, tooLarge
        /// Sukusho put it there from history; that entry was already moved to the top.
        case ownWrite
    }

    enum Content: Equatable, Sendable {
        case files, image, text
    }

    enum Decision: Equatable, Sendable {
        case skip(Skip), read(Content)
    }

    /// The first private marker among `types`, if any.
    static func privateMarker(in types: [String]) -> String? {
        types.first(where: privateTypes.contains)
    }

    static func decide(types: [String], sourceBundleID: String?, ignoredApps: Set<String>) -> Decision {
        if let marker = privateMarker(in: types) { return .skip(.privateType(marker)) }
        if let sourceBundleID, ignoredApps.contains(sourceBundleID) { return .skip(.ignoredApp(sourceBundleID)) }
        let hasImage = types.contains(where: imageTypes.contains)
        // Finder copies files with their icons as images; keep the files.
        if types.contains(fileURLType), sourceBundleID == "com.apple.finder" || !hasImage { return .read(.files) }
        if hasImage { return .read(.image) }
        if types.contains(where: textTypes.contains) || types.contains(colorType) { return .read(.text) }
        return .skip(.nothingKept)
    }

    /// Text that is a hex colour or a link is shown as one.
    static func textForm(_ text: String) -> ClipboardTextForm {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if let hex = hexColor(trimmed) ?? functionalColor(trimmed) { return .color(hex: hex) }
        if isLink(trimmed) { return .link }
        return .plain
    }

    /// "#ff6363" → "#FF6363"; also #RGB and #RRGGBBAA.
    static func hexColor(_ text: String) -> String? {
        guard text.hasPrefix("#") else { return nil }
        let digits = text.dropFirst()
        guard [3, 6, 8].contains(digits.count), digits.allSatisfy(\.isHexDigit) else { return nil }
        return "#" + digits.uppercased()
    }

    /// A hex `hexColor` gives, as sRGB components from 0 to 1.
    static func components(ofHex hex: String) -> (red: Double, green: Double, blue: Double, alpha: Double)? {
        var digits = String(hex.dropFirst())
        if digits.count == 3 { digits = digits.map { "\($0)\($0)" }.joined() }
        guard digits.count == 6 || digits.count == 8, let value = UInt64(digits, radix: 16) else { return nil }
        let hasAlpha = digits.count == 8
        let rgb = hasAlpha ? value >> 8 : value
        return (Double((rgb >> 16) & 0xFF) / 255, Double((rgb >> 8) & 0xFF) / 255, Double(rgb & 0xFF) / 255,
                hasAlpha ? Double(value & 0xFF) / 255 : 1)
    }

    /// rgb(), rgba(), hsl() and hsla() as CSS writes them, with commas or spaces, an alpha after "/" or a fourth
    /// value, percentages and "deg": the hex for their swatch, or nil (Fable #3: "rgb(10, 132, 255)" was plain text).
    static func functionalColor(_ text: String) -> String? {
        let lower = text.lowercased()
        guard let open = lower.firstIndex(of: "("), lower.hasSuffix(")") else { return nil }
        let name = String(lower[..<open])
        guard ["rgb", "rgba", "hsl", "hsla"].contains(name) else { return nil }
        // The two forms CSS writes: "a, b, c[, alpha]", or "a b c[ / alpha]". Nothing left empty, no slashes between
        // the channels (Astra R1: "rgb(1,,2,3)" and "rgb(1/2/3)" were taken as colors).
        let inner = String(lower[lower.index(after: open)..<lower.index(before: lower.endIndex)])
        var tokens: [String]
        if inner.contains(",") {
            guard !inner.contains("/") else { return nil }
            tokens = inner.split(separator: ",", omittingEmptySubsequences: false).map { $0.trimmingCharacters(in: .whitespaces) }
        } else {
            let parts = inner.split(separator: "/", omittingEmptySubsequences: false).map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count <= 2 else { return nil }
            tokens = parts[0].split(whereSeparator: \.isWhitespace).map(String.init)
            guard tokens.count == 3 else { return nil }
            if parts.count == 2 { tokens.append(parts[1]) }
        }
        guard tokens.count == 3 || tokens.count == 4, tokens.allSatisfy({ !$0.isEmpty && !$0.contains(where: \.isWhitespace) }) else {
            return nil
        }
        func number(_ token: String, percentOf full: Double, suffix: String = "") -> Double? {
            var token = token
            if !suffix.isEmpty, token.hasSuffix(suffix) { token.removeLast(suffix.count) }
            if token.hasSuffix("%") { return Double(token.dropLast()).map { $0 / 100 * full } }
            return Double(token)
        }
        let alpha = tokens.count == 4 ? number(tokens[3], percentOf: 1) : 1
        guard let alpha, (0...1).contains(alpha) else { return nil }
        var rgb: [Double]
        if name.hasPrefix("rgb") {
            let channels = tokens.prefix(3).compactMap { number($0, percentOf: 255) }
            guard channels.count == 3, channels.allSatisfy({ (0...255).contains($0) }) else { return nil }
            rgb = channels.map { $0 / 255 }
        } else {
            // A hue is degrees, never a percentage.
            guard !tokens[0].hasSuffix("%"), let degrees = number(tokens[0], percentOf: 360, suffix: "deg"),
                  tokens[1].hasSuffix("%"), tokens[2].hasSuffix("%"),
                  let saturation = number(tokens[1], percentOf: 1), let lightness = number(tokens[2], percentOf: 1),
                  (0...1).contains(saturation), (0...1).contains(lightness) else { return nil }
            // Into [0, 360), as CSS Color 4 does: -120° is 240° (Astra R1: it showed magenta, not blue).
            let hue = (degrees.truncatingRemainder(dividingBy: 360) + 360).truncatingRemainder(dividingBy: 360)
            // CSS Color 4's hsl-to-rgb.
            func channel(_ n: Double) -> Double {
                let k = (n + hue / 30).truncatingRemainder(dividingBy: 12)
                let a = saturation * min(lightness, 1 - lightness)
                return lightness - a * max(-1, min(k - 3, 9 - k, 1))
            }
            rgb = [channel(0), channel(8), channel(4)]
        }
        if alpha < 1 { rgb.append(alpha) }
        return "#" + rgb.map { String(format: "%02X", Int(($0 * 255).rounded())) }.joined()
    }

    /// One word with a scheme and "://", or a mailto: address.
    static func isLink(_ text: String) -> Bool {
        guard !text.isEmpty, !text.contains(where: \.isWhitespace),
              let scheme = URLComponents(string: text)?.scheme else { return false }
        return text.contains("://") || scheme.lowercased() == "mailto"
    }

    /// The capture's path when a copied file is one of Sukusho's own History
    /// files, so double-click can reopen that capture in the editor.
    static func libraryPath(of fileURL: URL?, historyDirectory: URL) -> String? {
        guard let path = fileURL?.standardizedFileURL.path else { return nil }
        let prefix = historyDirectory.standardizedFileURL.path + "/"
        return path.hasPrefix(prefix) ? path : nil
    }
}

@Suite
struct ClipboardCapturePolicyTests {
    private func decide(_ types: [String], from source: String? = "com.example.app",
                        ignoring ignored: Set<String> = []) -> ClipboardCapturePolicy.Decision {
        ClipboardCapturePolicy.decide(types: types, sourceBundleID: source, ignoredApps: ignored)
    }

    @Test func privateMarkersWinOverEverything() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            #expect(decide(["public.utf8-plain-text", "public.png", marker]) == .skip(.privateType(marker)))
        }
    }

    @Test func passwordAppsAreIgnoredByDefault() {
        let ignored = Set(ClipboardCapturePolicy.defaultIgnoredApps)
        #expect(decide(["public.utf8-plain-text"], from: "com.apple.Passwords", ignoring: ignored)
            == .skip(.ignoredApp("com.apple.Passwords")))
        #expect(decide(["public.utf8-plain-text"], from: "com.google.Chrome", ignoring: ignored) == .read(.text))
    }

    @Test func filesImagesAndText() {
        #expect(decide(["public.file-url", "public.tiff"], from: "com.apple.finder") == .read(.files))
        #expect(decide(["public.file-url"]) == .read(.files))
        #expect(decide(["public.file-url", "public.png"], from: "com.tommyent.Sukusho") == .read(.image))
        #expect(decide(["public.png", "public.utf8-plain-text"]) == .read(.image))
        #expect(decide(["com.apple.cocoa.pasteboard.color"]) == .read(.text))
        #expect(decide(["com.example.private-type"]) == .skip(.nothingKept))
    }

    @Test func textForms() {
        #expect(ClipboardCapturePolicy.textForm("#ff6363") == .color(hex: "#FF6363"))
        #expect(ClipboardCapturePolicy.textForm(" #FFF \n") == .color(hex: "#FFF"))
        #expect(ClipboardCapturePolicy.textForm("#12345") == .plain)
        #expect(ClipboardCapturePolicy.textForm("https://nspasteboard.org/") == .link)
        #expect(ClipboardCapturePolicy.textForm("slack://channel?team=T1") == .link)
        #expect(ClipboardCapturePolicy.textForm("mailto:someone@example.com") == .link)
        #expect(ClipboardCapturePolicy.textForm("require 'rubygems'") == .plain)
        #expect(ClipboardCapturePolicy.textForm("note: https://example.com") == .plain)
        #expect(ClipboardCapturePolicy.hexColor("#ff6363aa") == "#FF6363AA")
    }

    @Test func libraryPathOnlyInsideHistory() {
        let history = URL(fileURLWithPath: "/tmp/Sukusho/History", isDirectory: true)
        let inside = URL(fileURLWithPath: "/tmp/Sukusho/History/Screenshot.png")
        #expect(ClipboardCapturePolicy.libraryPath(of: inside, historyDirectory: history) == inside.path)
        #expect(ClipboardCapturePolicy.libraryPath(of: URL(fileURLWithPath: "/tmp/Sukusho/History2/a.png"),
                                                   historyDirectory: history) == nil)
        #expect(ClipboardCapturePolicy.libraryPath(of: nil, historyDirectory: history) == nil)
    }
}

@Suite
struct ClipboardPasteboardReaderTests {
    private let history = FileManager.default.temporaryDirectory
        .appendingPathComponent("ClipboardReaderTests-\(UUID().uuidString)/History", isDirectory: true)

    private func withPasteboard(_ items: [NSPasteboardItem], _ body: (NSPasteboard) throws -> Void) rethrows {
        let pasteboard = NSPasteboard(name: .init("SukushoClipboardTest-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.writeObjects(items)
        try body(pasteboard)
    }

    private func read(_ pasteboard: NSPasteboard, front: String? = "com.example.front") -> ClipboardPasteboardReader.Outcome {
        ClipboardPasteboardReader.read(pasteboard, changeCount: pasteboard.changeCount, frontmostBundleID: front,
                                       ignoredApps: [], historyDirectory: history).outcome
    }

    private func item(_ values: [String: String] = [:], data: [String: Data] = [:]) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        for (type, value) in values { item.setString(value, forType: .init(type)) }
        for (type, value) in data { item.setData(value, forType: .init(type)) }
        return item
    }

    private func image(width: Int, height: Int, as type: NSBitmapImageRep.FileType) throws -> Data {
        let rep = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height,
                                                bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                                colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        return try #require(rep.representation(using: type, properties: [:]))
    }

    @Test func textKeepsRichTextAndTheSourceMarker() throws {
        let rtf = Data("{\\rtf1 Hello}".utf8)
        withPasteboard([item(["public.utf8-plain-text": "Hello", "org.nspasteboard.source": "com.example.source"],
                                 data: ["public.rtf": rtf])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard) else { Issue.record("not captured"); return }
            #expect(capture.kind == .text)
            #expect(capture.text == "Hello")
            #expect(capture.richText["public.rtf"] == rtf)
            #expect(capture.sourceBundleID == "com.example.source")
            #expect(capture.hash == ClipboardPasteboardReader.digest(Data("Hello".utf8)))
        }
    }

    @Test func noMarkerCreditsTheFrontApp() throws {
        withPasteboard([item(["public.utf8-plain-text": "x"])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard, front: "com.google.Chrome") else { Issue.record("not captured"); return }
            #expect(capture.sourceBundleID == "com.google.Chrome")
        }
    }

    @Test func aHexColourIsKeptAsCopiedText() throws {
        withPasteboard([item(["public.utf8-plain-text": "#ff6363\n"])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard) else { Issue.record("not captured"); return }
            #expect(capture.kind == .text)
            #expect(capture.text == "#ff6363\n")
            #expect(ClipboardCapturePolicy.textForm(capture.text ?? "") == .color(hex: "#FF6363"))
        }
    }

    @Test func tiffIsKeptAsPNG() throws {
        let tiff = try image(width: 4, height: 3, as: .tiff)
        withPasteboard([item(data: ["public.tiff": tiff])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard) else { Issue.record("not captured"); return }
            #expect(capture.kind == .image)
            #expect(capture.imageExtension == "png")
            #expect(capture.image?.prefix(4) == Data([0x89, 0x50, 0x4E, 0x47]))
            #expect(capture.pixelWidth == 4 && capture.pixelHeight == 3)
            #expect(capture.hash == ClipboardPasteboardReader.digest(tiff))
        }
    }

    @Test func aSukushoCaptureStaysInTheLibrary() throws {
        let png = try image(width: 8, height: 8, as: .png)
        let file = history.appendingPathComponent("Screenshot 2026-11-16.png")
        withPasteboard([item(["public.file-url": file.absoluteString, "org.nspasteboard.source": "com.tommyent.Sukusho"],
                                 data: ["public.png": png])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard) else { Issue.record("not captured"); return }
            #expect(capture.kind == .image)
            #expect(capture.libraryPath == file.path)
            #expect(capture.image == nil)
            #expect(capture.storedBytes == 0)
            #expect(capture.byteSize == png.count)
        }
    }

    @Test func concealedCopiesAreNeverRead() throws {
        withPasteboard([item(["public.utf8-plain-text": "hunter2", "org.nspasteboard.ConcealedType": ""])]) { pasteboard in
            #expect(read(pasteboard) == .skipped(.privateType("org.nspasteboard.ConcealedType")))
        }
    }

    @Test func oversizedTextIsSkipped() throws {
        let text = String(repeating: "a", count: ClipboardCapturePolicy.maxTextBytes + 1)
        withPasteboard([item(["public.utf8-plain-text": text])]) { pasteboard in
            #expect(read(pasteboard) == .skipped(.tooLarge))
        }
    }

    @Test func aCopyReplacedMidReadIsDropped() throws {
        withPasteboard([item(["public.utf8-plain-text": "first"])]) { pasteboard in
            let outcome = ClipboardPasteboardReader.read(pasteboard, changeCount: pasteboard.changeCount - 1,
                                                         frontmostBundleID: nil, ignoredApps: [], historyDirectory: history).outcome
            #expect(outcome == .changed)
        }
    }

    @Test func readsOffTheMainThread() async throws {
        let name = "SukushoClipboardTest-\(UUID().uuidString)"
        let pasteboard = NSPasteboard(name: .init(name))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.setString("off main", forType: .string)
        let history = history
        let outcome = await Task.detached {
            let pasteboard = NSPasteboard(name: .init(name))
            return ClipboardPasteboardReader.read(pasteboard, changeCount: pasteboard.changeCount, frontmostBundleID: nil,
                                                  ignoredApps: [], historyDirectory: history).outcome
        }.value
        guard case .captured(let capture) = outcome else { Issue.record("not captured"); return }
        #expect(capture.text == "off main")
    }
}

@Suite
struct ClipboardHistoryStoreTests {
    private let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("ClipboardStoreTests-\(UUID().uuidString)", isDirectory: true)
    private let day: TimeInterval = 86_400
    private let start = Date(timeIntervalSince1970: 1_800_000_000)

    private func store() throws -> ClipboardHistoryStore {
        try ClipboardHistoryStore(directory: directory, deviceID: "test-mac")
    }

    private func text(_ value: String) -> ClipboardCapture {
        ClipboardCapture(kind: .text, hash: ClipboardPasteboardReader.digest(Data(value.utf8)), text: value,
                         byteSize: value.utf8.count)
    }

    private func image(_ size: Int, width: Int = 1, height: Int = 1) -> ClipboardCapture {
        image(Data(UUID().uuidString.utf8) + Data(repeating: 7, count: size - 36), width: width, height: height)
    }

    private func image(_ data: Data, width: Int, height: Int, source: String? = nil) -> ClipboardCapture {
        var capture = ClipboardCapture(kind: .image, hash: ClipboardPasteboardReader.digest(data), image: data,
                                       imageExtension: "png", pixelWidth: width, pixelHeight: height, byteSize: data.count)
        capture.sourceBundleID = source
        return capture
    }

    @Test func copyingAgainBumpsTheSameEntry() async throws {
        let store = try store()
        let first = try await store.record(text("same"), at: start)
        guard case .inserted(let id) = first else { Issue.record("not inserted"); return }
        #expect(try await store.record(text("same"), at: start + 60) == .bumped(id))
        let entries = try await store.entries()
        #expect(entries.count == 1)
        #expect(entries[0].timesCopied == 2)
        #expect(entries[0].firstCopiedAt == start)
        #expect(entries[0].lastCopiedAt == start + 60)
    }

    @Test func newestFirstWithRichText() async throws {
        let store = try store()
        var rich = text("rich")
        rich.richText = ["public.html": Data("<b>rich</b>".utf8)]
        try await store.record(rich, at: start)
        try await store.record(text("newer"), at: start + 1)
        let entries = try await store.entries()
        #expect(entries.map(\.text) == ["newer", "rich"])
        #expect(try await store.richText(for: entries[1].id) == ["public.html": Data("<b>rich</b>".utf8)])
    }

    @Test func anImageIsAFileThatGoesWithItsEntry() async throws {
        let store = try store()
        try await store.record(image(1000), at: start)
        let entry = try #require(try await store.entries().first)
        let url = try #require(entry.imageURL)
        #expect(FileManager.default.fileExists(atPath: url.path))
        try await store.delete(entry.id)
        #expect(!FileManager.default.fileExists(atPath: url.path))
        #expect(try await store.entries().isEmpty)
    }

    @Test func retentionSparesPinsAndSnippets() async throws {
        let store = try store()
        try await store.record(text("old"), at: start)
        guard case .inserted(let pinned) = try await store.record(text("old pinned"), at: start) else { return }
        try await store.setPinned(pinned, true)
        try await store.addSnippet(title: "Bug report", text: "Steps:", at: start)
        try await store.record(text("recent"), at: start + 40 * day)
        let dropped = try await store.sweep(now: start + 41 * day, retention: 30 * day, maxBytes: .max)
        #expect(dropped == 1)
        #expect(Set(try await store.entries().compactMap(\.text)) == ["old pinned", "Steps:", "recent"])
    }

    @Test func sizeCapDropsTheOldestUnpinnedFirst() async throws {
        let store = try store()
        // Different sizes, so none of them counts as a rewrite of the one before.
        guard case .inserted(let oldest) = try await store.record(image(1000, width: 1), at: start) else { return }
        try await store.setPinned(oldest, true)
        try await store.record(image(1000, width: 2), at: start + 1)
        guard case .inserted(let newest) = try await store.record(image(1000, width: 3), at: start + 2) else { return }
        #expect(try await store.totalBytes() == 3000)
        try await store.sweep(now: start + 3, retention: nil, maxBytes: 2000)
        #expect(Set(try await store.entries().map(\.id)) == [oldest, newest])
        #expect(try await store.totalBytes() == 2000)
    }

    @Test func aDeletedLibraryCaptureTakesItsEntry() async throws {
        let store = try store()
        let file = directory.appendingPathComponent("capture.png")
        try Data([1]).write(to: file)
        var capture = image(100)
        capture.image = nil
        capture.libraryPath = file.path
        try await store.record(capture, at: start)
        #expect(try await store.sweep(now: start, retention: nil, maxBytes: .max) == 0)
        try FileManager.default.removeItem(at: file)
        #expect(try await store.sweep(now: start, retention: nil, maxBytes: .max) == 1)
        #expect(try await store.entries().isEmpty)
    }

    @Test func entriesSurviveReopening() async throws {
        try await store().record(text("kept"), at: start)
        #expect(try await store().entries().map(\.text) == ["kept"])
    }

    @Test func touchMovesAnEntryToTheTop() async throws {
        let store = try store()
        guard case .inserted(let older) = try await store.record(text("older"), at: start) else { return }
        try await store.record(text("newer"), at: start + 1)
        try await store.touch(older, at: start + 2)
        let entries = try await store.entries()
        #expect(entries.map(\.text) == ["older", "newer"])
        #expect(entries[0].timesCopied == 2)
    }

    @Test func deletingHistoryKeepsSnippets() async throws {
        let store = try store()
        try await store.record(image(500), at: start)
        try await store.record(text("gone"), at: start)
        try await store.addSnippet(title: "Kept", text: "body", at: start)
        try await store.deleteHistory()
        #expect(try await store.entries().map(\.title) == ["Kept"])
        #expect(try await store.totalBytes() == 4)
    }

    /// An optimiser such as Clop puts a smaller version of the image back on the clipboard a moment later
    /// (2026-11-16 on the owner's Air: two entries per screenshot). History keeps one entry with the new bytes.
    @Test func anOptimisersRewriteReplacesTheCopyBefore() async throws {
        let store = try store()
        let file = directory.appendingPathComponent("capture.png")
        var original = image(Data(repeating: 1, count: 79_041), width: 359, height: 815, source: "com.tommyent.Sukusho")
        original.image = nil
        original.libraryPath = file.path
        guard case .inserted(let id) = try await store.record(original, at: start) else { Issue.record("not inserted"); return }
        let rewrite = image(Data(repeating: 2, count: 22_523), width: 359, height: 815, source: "com.apple.Terminal")
        #expect(try await store.record(rewrite, at: start + 0.5) == .replaced(id))
        let entries = try await store.entries()
        #expect(entries.count == 1)
        let entry = try #require(entries.first)
        #expect(entry.byteSize == 22_523)
        #expect(entry.libraryPath == file.path)
        #expect(entry.sourceBundleID == "com.tommyent.Sukusho")
        #expect(entry.timesCopied == 1)
        #expect(entry.firstCopiedAt == start)
        let url = try #require(entry.imageURL)
        #expect(try Data(contentsOf: url) == rewrite.image)
        #expect(try await store.totalBytes() == 22_523)
    }

    @Test func aNewCopyIsNotARewrite() async throws {
        // A different size, a copy after the window, a copy in between, a pinned or a repeated entry: all kept.
        let cases: [(String, (ClipboardHistoryStore) async throws -> Void)] = [
            ("size", { try await $0.record(self.image(500, width: 10, height: 10), at: self.start + 1) }),
            ("window", { try await $0.record(self.image(500, width: 359, height: 815), at: self.start + 11) }),
            ("between", { store in
                try await store.record(self.text("in between"), at: self.start + 1)
                try await store.record(self.image(500, width: 359, height: 815), at: self.start + 2)
            }),
        ]
        for (name, then) in cases {
            let store = try ClipboardHistoryStore(
                directory: directory.appendingPathComponent(name, isDirectory: true), deviceID: "test-mac")
            try await store.record(image(500, width: 359, height: 815), at: start)
            try await then(store)
            #expect(try await store.entries().filter { $0.kind == .image }.count == 2, "\(name)")
        }
        let pinnedStore = try ClipboardHistoryStore(
            directory: directory.appendingPathComponent("pinned", isDirectory: true), deviceID: "test-mac")
        guard case .inserted(let pinned) = try await pinnedStore.record(image(500, width: 359, height: 815), at: start) else { return }
        try await pinnedStore.setPinned(pinned, true)
        try await pinnedStore.record(image(500, width: 359, height: 815), at: start + 1)
        #expect(try await pinnedStore.entries().count == 2)
    }

    @Test func copyingAnOptimisedImageAgainKeepsOneEntry() async throws {
        let store = try store()
        let original = Data(repeating: 1, count: 900), optimised = Data(repeating: 2, count: 300)

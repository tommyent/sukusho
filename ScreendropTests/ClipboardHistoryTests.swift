@Suite
struct ClipboardWriterTests {
    private func entry(_ kind: ClipboardEntryKind, _ text: String?, source: String? = "com.google.Chrome",
                       image: URL? = nil) -> ClipboardEntry {
        ClipboardEntry(id: "1", kind: kind, text: text, title: nil, imageURL: image, libraryPath: nil, byteSize: 0,
                       pixelWidth: 0, pixelHeight: 0, sourceBundleID: source, isRemote: false,
                       firstCopiedAt: .now, lastCopiedAt: .now, timesCopied: 1, pinnedAt: nil)
    }

    private func withPasteboard(_ body: (NSPasteboard) throws -> Void) rethrows {
        let pasteboard = NSPasteboard(name: .init("SukushoClipboardTest-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        try body(pasteboard)
    }

    @Test func aPasteBackNamesTheOriginalAppAndIsMarkedAutoGenerated() {
        withPasteboard { pasteboard in
            let rtf = Data("{\\rtf1 hi}".utf8)
            #expect(ClipboardWriter.write(entry(.text, "hi"), richText: ["public.rtf": rtf], plain: false, to: pasteboard))
            let item = pasteboard.pasteboardItems?.first
            #expect(item?.string(forType: .string) == "hi")
            #expect(item?.data(forType: .init("public.rtf")) == rtf)
            #expect(item?.string(forType: .init("org.nspasteboard.source")) == "com.google.Chrome")
            #expect(item?.types.contains(.init("org.nspasteboard.AutoGeneratedType")) == true)
            #expect(item?.types.contains(.init(ClipboardCapturePolicy.ownType)) == true)
            // and Sukusho's own monitor leaves it alone
            let outcome = ClipboardPasteboardReader.read(pasteboard, changeCount: pasteboard.changeCount, frontmostBundleID: nil,
                                                         ignoredApps: [], historyDirectory: URL(fileURLWithPath: "/tmp/History")).outcome
            #expect(outcome == .skipped(.ownWrite))
        }
    }

    @Test func plainTextDropsFormatting() {
        withPasteboard { pasteboard in
            ClipboardWriter.write(entry(.text, "hi"), richText: ["public.rtf": Data("{\\rtf1 hi}".utf8)], plain: true, to: pasteboard)
            #expect(pasteboard.pasteboardItems?.first?.data(forType: .init("public.rtf")) == nil)
            #expect(pasteboard.string(forType: .string) == "hi")
        }
    }

    @Test func filesGoBackAsFileURLs() {
        withPasteboard { pasteboard in
            ClipboardWriter.write(entry(.files, "/tmp/a.txt\n/tmp/b.txt"), richText: [:], plain: false, to: pasteboard)
            let urls = pasteboard.pasteboardItems?.compactMap { $0.string(forType: .fileURL) }
            #expect(urls == [URL(fileURLWithPath: "/tmp/a.txt").absoluteString, URL(fileURLWithPath: "/tmp/b.txt").absoluteString])
        }
    }

    @Test func aMissingImageFileIsNotWritten() {
        withPasteboard { pasteboard in
            let gone = URL(fileURLWithPath: "/tmp/SukushoClipboardTest-\(UUID().uuidString).png")
            #expect(!ClipboardWriter.write(entry(.image, nil, image: gone), richText: [:], plain: false, to: pasteboard))
        }
    }
}

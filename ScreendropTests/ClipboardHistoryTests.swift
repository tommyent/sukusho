    }
}

@Suite
struct ClipboardListTests {
    private var calendar: Calendar {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "UTC")!
        return calendar
    }
    private let now = Date(timeIntervalSince1970: 1_800_000_000) // a Friday, 08:00 UTC

    private func entry(_ kind: ClipboardEntryKind = .text, _ text: String? = nil, title: String? = nil,
                       ago: TimeInterval = 0, pinnedAgo: TimeInterval? = nil, source: String? = nil,
                       size: (Int, Int) = (0, 0), image: String? = nil) -> ClipboardEntry {
        ClipboardEntry(id: UUID().uuidString, kind: kind, text: text, title: title,
                       imageURL: image.map { URL(fileURLWithPath: "/tmp/\($0)") }, libraryPath: nil, byteSize: 0,
                       pixelWidth: size.0, pixelHeight: size.1, sourceBundleID: source, isRemote: false,
                       firstCopiedAt: now - ago, lastCopiedAt: now - ago, timesCopied: 1,
                       pinnedAt: pinnedAgo.map { now - $0 })
    }

    @Test func arrowsMoveTheSelectionInsideTheGrid() {
        let ids = ["a", "b", "c", "d", "e"]
        #expect(ClipboardList.move(from: nil, by: 1, in: ids) == "a")
        #expect(ClipboardList.move(from: "a", by: 1, in: ids) == "b")
        #expect(ClipboardList.move(from: "b", by: 3, in: ids) == "e")
        #expect(ClipboardList.move(from: "d", by: 3, in: ids) == "e")
        #expect(ClipboardList.move(from: "a", by: -1, in: ids) == nil)
        #expect(ClipboardList.move(from: "gone", by: 1, in: ids) == "a")
        #expect(ClipboardList.move(from: "a", by: 1, in: []) == nil)
    }

    @Test func anImageIsNamedByTheModelAndFoundByItsText() {
        var described = entry(.image, size: (1600, 1000))
        described.modelTitle = "Xcode build failure in AgentAccessServer"
        described.readText = "Build Failed\nCall can throw but is not marked"
        described.keywords = ["Xcode"]
        let plain = entry(.image, size: (359, 815))
        #expect(ClipboardList.title(of: described) == "Xcode build failure in AgentAccessServer")
        #expect(ClipboardList.title(of: plain) == "Image (359×815)")
        let found = ClipboardList.sections([described, plain], filter: .all, query: CaptureLibraryQuery("not marked"), now: now,
                                           calendar: calendar)
        #expect(found.flatMap(\.entries).map(\.id) == [described.id])
        #expect(ClipboardList.matches(described, query: CaptureLibraryQuery("xcode"), appName: nil))
    }

    @Test func pinnedThenTodayYesterdayEarlier() {
        let entries = [
            entry(.text, "this morning", ago: 3600),
            entry(.text, "yesterday", ago: 86_400),
            entry(.text, "last week", ago: 7 * 86_400),
            entry(.text, "pinned long ago", ago: 30 * 86_400, pinnedAgo: 60),
            entry(.snippet, "body", title: "A snippet"),
        ]
        let sections = ClipboardList.sections(entries, filter: .all, query: CaptureLibraryQuery(""), now: now, calendar: calendar)
        #expect(sections.map(\.title) == ["Pinned", "Today", "Yesterday", "Earlier"])

@Suite
struct ClipboardCapturePolicyTests {
    private func decide(_ types: [String], from source: String? = "com.example.app",
                        ignoring ignored: Set<String> = []) -> ClipboardCapturePolicy.Decision {
        ClipboardCapturePolicy.decide(types: types, sourceBundleID: source, ignoredApps: ignored)
    }

    @Test func privateMarkersWinOverEverything() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            #expect(decide(["public.utf8-plain-text", "public.png", marker]) == .skip(.privateType(marker)))
        }
    }

    @Test func passwordAppsAreIgnoredByDefault() {
        let ignored = Set(ClipboardCapturePolicy.defaultIgnoredApps)
        #expect(decide(["public.utf8-plain-text"], from: "com.apple.Passwords", ignoring: ignored)
            == .skip(.ignoredApp("com.apple.Passwords")))
        #expect(decide(["public.utf8-plain-text"], from: "com.google.Chrome", ignoring: ignored) == .read(.text))
    }

    @Test func filesImagesAndText() {
        #expect(decide(["public.file-url", "public.tiff"], from: "com.apple.finder") == .read(.files))
        #expect(decide(["public.file-url"]) == .read(.files))
        #expect(decide(["public.file-url", "public.png"], from: "com.tommyent.Sukusho") == .read(.image))
        #expect(decide(["public.png", "public.utf8-plain-text"]) == .read(.image))
        #expect(decide(["com.apple.cocoa.pasteboard.color"]) == .read(.text))
        #expect(decide(["com.example.private-type"]) == .skip(.nothingKept))
    }

    @Test func textForms() {
        #expect(ClipboardCapturePolicy.textForm("#ff6363") == .color(hex: "#FF6363"))
        #expect(ClipboardCapturePolicy.textForm(" #FFF \n") == .color(hex: "#FFF"))
        #expect(ClipboardCapturePolicy.textForm("#12345") == .plain)
        #expect(ClipboardCapturePolicy.textForm("https://nspasteboard.org/") == .link)
        #expect(ClipboardCapturePolicy.textForm("slack://channel?team=T1") == .link)
        #expect(ClipboardCapturePolicy.textForm("mailto:someone@example.com") == .link)
        #expect(ClipboardCapturePolicy.textForm("require 'rubygems'") == .plain)
        #expect(ClipboardCapturePolicy.textForm("note: https://example.com") == .plain)
        #expect(ClipboardCapturePolicy.hexColor("#ff6363aa") == "#FF6363AA")
    }

    @Test func libraryPathOnlyInsideHistory() {
        let history = URL(fileURLWithPath: "/tmp/Sukusho/History", isDirectory: true)
        let inside = URL(fileURLWithPath: "/tmp/Sukusho/History/Screenshot.png")
        #expect(ClipboardCapturePolicy.libraryPath(of: inside, historyDirectory: history) == inside.path)
        #expect(ClipboardCapturePolicy.libraryPath(of: URL(fileURLWithPath: "/tmp/Sukusho/History2/a.png"),
                                                   historyDirectory: history) == nil)
        #expect(ClipboardCapturePolicy.libraryPath(of: nil, historyDirectory: history) == nil)
    }
}

@Suite
struct ClipboardPasteboardReaderTests {
    private let history = FileManager.default.temporaryDirectory
        .appendingPathComponent("ClipboardReaderTests-\(UUID().uuidString)/History", isDirectory: true)

    private func withPasteboard(_ items: [NSPasteboardItem], _ body: (NSPasteboard) throws -> Void) rethrows {
        let pasteboard = NSPasteboard(name: .init("SukushoClipboardTest-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.writeObjects(items)
        try body(pasteboard)
    }

    private func read(_ pasteboard: NSPasteboard, front: String? = "com.example.front") -> ClipboardPasteboardReader.Outcome {
        ClipboardPasteboardReader.read(pasteboard, changeCount: pasteboard.changeCount, frontmostBundleID: front,
                                       ignoredApps: [], historyDirectory: history).outcome
    }

    private func item(_ values: [String: String] = [:], data: [String: Data] = [:]) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        for (type, value) in values { item.setString(value, forType: .init(type)) }
        for (type, value) in data { item.setData(value, forType: .init(type)) }
        return item
    }

    private func image(width: Int, height: Int, as type: NSBitmapImageRep.FileType) throws -> Data {
        let rep = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height,
                                                bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                                colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        return try #require(rep.representation(using: type, properties: [:]))
    }

    @Test func textKeepsRichTextAndTheSourceMarker() throws {
        let rtf = Data("{\\rtf1 Hello}".utf8)
        withPasteboard([item(["public.utf8-plain-text": "Hello", "org.nspasteboard.source": "com.example.source"],
                                 data: ["public.rtf": rtf])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard) else { Issue.record("not captured"); return }
            #expect(capture.kind == .text)
            #expect(capture.text == "Hello")
            #expect(capture.richText["public.rtf"] == rtf)
            #expect(capture.sourceBundleID == "com.example.source")
            #expect(capture.hash == ClipboardPasteboardReader.digest(Data("Hello".utf8)))
        }
    }

    @Test func noMarkerCreditsTheFrontApp() throws {
        withPasteboard([item(["public.utf8-plain-text": "x"])]) { pasteboard in
            guard case .captured(let capture) = read(pasteboard, front: "com.google.Chrome") else { Issue.record("not captured"); return }
            #expect(capture.sourceBundleID == "com.google.Chrome")
